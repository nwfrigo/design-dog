/**
 * PDF-safe shadow/glow: a pre-rendered transparent PNG stretched behind a
 * rounded element, in place of CSS `box-shadow`.
 *
 * Why: templates exported through Puppeteer's `page.pdf()` (vector-PDF
 * pipeline — industry-roi, and any future long-page PDF template) cannot use
 * CSS box-shadows or alpha-gradient fades. Chromium's print engine encodes
 * them as soft-masked shadings, which render as hard rectangular banding in
 * most viewers and as solid magenta in pdf.js-based ones (Firefox, Highspot,
 * Seismic, SharePoint previews). A transparent PNG becomes a plain alpha-
 * masked image in the PDF, which every renderer handles. Templates exported
 * as PNG screenshots are unaffected and can keep plain `box-shadow`.
 *
 * The PNG assets are generated by `scripts/generate-roi-overlays.mjs` — add
 * new shadow specs there. Because a blur is diffuse, stretching one PNG a few
 * px to fit variable element sizes is invisible; generate the asset near the
 * real element size.
 *
 * Usage: the host element needs `position: relative` (plus a `position` on
 * any children that must paint above the glow), overflow visible, and this as
 * its first child with `spread` ≥ the shadow's blur radius, matching the
 * margin the asset was generated with.
 */
export function RasterShadow({ src, spread }: { src: string; spread: number }) {
  return (
    // eslint-disable-next-line @next/next/no-img-element
    <img
      src={src}
      alt=""
      style={{
        position: 'absolute', left: -spread, top: -spread,
        width: `calc(100% + ${spread * 2}px)`, height: `calc(100% + ${spread * 2}px)`,
        maxWidth: 'none', pointerEvents: 'none',
      }}
    />
  )
}
